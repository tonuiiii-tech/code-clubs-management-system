/**
 * Writes docs/kiswahili-review.md: every Kiswahili text in the app beside its English, grouped
 * by screen, for a native speaker at STEAMLabs to check (Sprint 5, question 6).
 *
 *   npm run i18n:review --workspace client
 *
 * Corrections go into client/src/i18n/locales/sw/common.json; then run this again.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../..', import.meta.url));
const read = (lang) =>
  JSON.parse(readFileSync(`${root}client/src/i18n/locales/${lang}/common.json`, 'utf8'));
const en = read('en');
const sw = read('sw');

// Where each group of texts appears, in the order a reviewer meets them.
const SCREENS = [
  ['Sign in and layout', ['app', 'nav', 'language', 'login', 'demo', 'common', 'errors']],
  ['Dashboard and alerts', ['dashboard', 'hq', 'alerts']],
  ['Schools and clubs', ['schools', 'clubs', 'schoolTypes', 'venueTypes', 'days', 'frequencies']],
  [
    'Users and profile',
    ['users', 'profile', 'roles', 'championTypes', 'safeguarding', 'assignmentRoles'],
  ],
  [
    'Learners and consent',
    [
      'learners',
      'consent',
      'consentStatuses',
      'genders',
      'grades',
      'relationships',
      'learnerStatuses',
    ],
  ],
  ['Sessions and attendance', ['sessions', 'sessionStatuses', 'attendanceStatuses']],
  [
    'Events and announcements',
    ['events', 'eventTypes', 'eventStatuses', 'participantStatuses', 'announcements'],
  ],
  ['Equipment', ['equipment', 'equipmentTypes', 'equipmentConditions']],
  ['Resources', ['resources', 'resourceTypes', 'resourceStatuses']],
  ['Projects, assessments and progress', ['projects', 'assessments', 'progress']],
  ['Reports and settings', ['reports', 'settings', 'channels', 'messageStatuses']],
  ['Sync (working offline)', ['sync']],
  ['Shared words', ['status', 'regions', 'tracks', 'validation']],
  ['Error messages from the server', ['apiErrors']],
];

function flatten(object, prefix = '') {
  return Object.entries(object).flatMap(([key, value]) =>
    value && typeof value === 'object'
      ? flatten(value, `${prefix}${key}.`)
      : [[`${prefix}${key}`, value]],
  );
}

const cell = (text) =>
  String(text ?? '**missing**')
    .replaceAll('|', '\\|')
    .replaceAll('\n', ' ');
const swFlat = new Map(flatten(sw));
const listed = new Set(SCREENS.flatMap(([, groups]) => groups));
const others = Object.keys(en).filter((group) => !listed.has(group));
const screens = others.length ? [...SCREENS, ['Other', others]] : SCREENS;
let count = 0;

const sections = screens.map(([title, groups]) => {
  const rows = groups.flatMap((group) => flatten(en[group] ?? {}, `${group}.`));
  count += rows.length;
  return [
    `## ${title}`,
    '',
    '| Key | English | Kiswahili | Correction |',
    '| --- | --- | --- | --- |',
    ...rows.map(([key, text]) => `| \`${key}\` | ${cell(text)} | ${cell(swFlat.get(key))} | |`),
    '',
  ].join('\n');
});

const doc = [
  '# Kiswahili review list',
  '',
  `Every Kiswahili text in the app (${count} texts), beside the English, grouped by screen. Generated by \`client/scripts/kiswahili-review.js\`; do not edit by hand.`,
  '',
  'How to review: read the Kiswahili as a champion or coordinator would. Where it is wrong, unclear or too formal, write the better text in the Correction column (or comment on the pull request). Words in `{{double braces}}` are filled in by the app (a number, a name or a date) and must stay as they are. Texts ending in `_one` and `_other` are the singular and plural of the same message.',
  '',
  ...sections,
].join('\n');

writeFileSync(`${root}docs/kiswahili-review.md`, doc);
console.log(`Wrote docs/kiswahili-review.md with ${count} texts.`);
